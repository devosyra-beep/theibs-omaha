'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname,'..');
const normalize = value=>value.replace(/\r\n?/g,'\n');
const hash = value=>crypto.createHash('sha256').update(value).digest('hex');
function generate() {
  const modules = new Map(), nodeDependencies = new Set();
  function visit(id) {
    if(modules.has(id))return;
    const raw = normalize(fs.readFileSync(path.join(root,id),'utf8'));
    const source = id.endsWith('.json') ? `module.exports = ${JSON.stringify(JSON.parse(raw))};` : raw;
    const dependencies = {}; modules.set(id,{source,raw,dependencies});
    const calls = [...source.matchAll(/\brequire\s*\(\s*(['"])([^'"]+)\1\s*\)/g)];
    if(calls.length !== [...source.matchAll(/\brequire\s*\(/g)].length)throw Error(`Dynamic require: ${id}`);
    for(const match of calls) {
      const specifier = match[2];
      if(specifier.startsWith('node:')) {
        if(!['node:crypto','node:perf_hooks'].includes(specifier))throw Error(`Unsupported dependency: ${specifier} in ${id}`);
        nodeDependencies.add(specifier);dependencies[specifier]=specifier;
      } else {
        if(!specifier.startsWith('.'))throw Error(`External dependency: ${specifier}`);
        const target=path.resolve(root,path.dirname(id),/\.(js|json)$/.test(specifier)?specifier:`${specifier}.js`);
        const relative=path.relative(root,target).split(path.sep).join('/');
        if(relative.startsWith('../')||path.isAbsolute(relative))throw Error('Dependency escapes source.');
        dependencies[specifier]=relative;visit(relative);
      }
    }
    if(/\bBuffer\b|\b__dirname\b|\b__filename\b|\bprocess\./.test(source))throw Error(`Unsupported Node global: ${id}`);
  }
  for(const id of ['src/multiway-compute-request.js','src/continuation-strategy.js','src/fast-evaluator.js'])visit(id);
  const ids=[...modules.keys()].sort(), runtimeFiles=['scripts/browser-solver/runtime-adapters.js','scripts/browser-multiway/worker-entry.js'];
  const runtime=runtimeFiles.map(id=>({id,source:normalize(fs.readFileSync(path.join(root,id),'utf8'))}));
  const descriptor={schemaVersion:1,runtimeVersion:'THEIBS_BROWSER_MULTIWAY_V1',engineBuild:require('../package.json').version,
    model:require('../src/multiway-evaluator').MODEL,builderSha256:hash(normalize(fs.readFileSync(__filename,'utf8'))),
    sources:ids.map(id=>({id,sha256:hash(modules.get(id).raw),bytes:Buffer.byteLength(modules.get(id).raw)})),
    runtimeSources:runtime.map(({id,source})=>({id,sha256:hash(source)})),nodeAdapters:[...nodeDependencies].sort(),
    cancellation:'HOST_WORKER_TERMINATE',cache:'OWNER_BUILD_FULL_INPUT_COMPLETE_ONLY',sourceNormalization:'LF'};
  const manifest={...descriptor,buildFingerprint:hash(JSON.stringify(descriptor))};
  const wrappers=ids.map(id=>`${JSON.stringify(id)}:function(module,exports,require){\n${modules.get(id).source}\n}`).join(',\n');
  const maps=Object.fromEntries(ids.map(id=>[id,modules.get(id).dependencies]));
  const source=`// Generated by scripts/build-browser-multiway.cjs; edit authoritative sources.\n(function(){\n'use strict';\nconst browserMultiwayManifest=${JSON.stringify(manifest)};\n${runtime[0].source}\nconst browserModules={\n${wrappers}\n};\nconst browserDependencyMaps=${JSON.stringify(maps)};\nconst browserModuleCache=Object.create(null);\nfunction requireBrowserModule(id){\nif(Object.hasOwn(browserNodeAdapters,id))return browserNodeAdapters[id];\nif(Object.hasOwn(browserModuleCache,id))return browserModuleCache[id].exports;\nif(!Object.hasOwn(browserModules,id))throw Error('Unknown module: '+id);\nconst module={exports:{}};browserModuleCache[id]=module;\nbrowserModules[id](module,module.exports,specifier=>{const target=browserDependencyMaps[id][specifier];if(!target)throw Error('Unknown dependency: '+specifier);return requireBrowserModule(target);});\nreturn module.exports;\n}\n${runtime[1].source}\n})();\n`;
  return {source,manifest};
}
function main(args=process.argv.slice(2)) {
  if(args.some(arg=>arg!=='--check'))throw Error('Use build-browser-multiway.cjs [--check].');
  const output=generate();
  for(const [id,expected] of [['public/browser-multiway-worker.js',output.source],['public/browser-multiway-manifest.json',JSON.stringify(output.manifest,null,2)+'\n']]) {
    const file=path.join(root,id);
    if(args.includes('--check')) {if(!fs.existsSync(file)||normalize(fs.readFileSync(file,'utf8'))!==expected)throw Error(`${id} is stale.`);}
    else fs.writeFileSync(file,expected);
  }
  console.log(JSON.stringify({status:args.includes('--check')?'CURRENT':'BUILT',buildFingerprint:output.manifest.buildFingerprint,modules:output.manifest.sources.length,workerBytes:Buffer.byteLength(output.source)}));
}
if(require.main===module){try{main();}catch(error){console.error(error.message);process.exitCode=1;}}
module.exports={generate,normalize};
