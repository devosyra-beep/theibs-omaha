'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname,'..');
const entry = 'src/solver/job-worker.js';
const runtimeVersion = 'THEIBS_BROWSER_SOLVER_V1';
const normalize = value=>value.replace(/\r\n?/g,'\n');
const hash = value=>crypto.createHash('sha256').update(value).digest('hex');
const adapters = new Set(['node:crypto','node:perf_hooks','node:worker_threads']);
function generate() {
  const modules = new Map(), nodeDependencies = new Set();
  function visit(id) {
    if (modules.has(id)) return;
    const source = normalize(fs.readFileSync(path.join(root,id),'utf8'));
    const dependencies = {};
    modules.set(id,{source,dependencies});
    const calls = [...source.matchAll(/\brequire\s*\(\s*(['"])([^'"]+)\1\s*\)/g)];
    if (calls.length !== [...source.matchAll(/\brequire\s*\(/g)].length) throw Error(`A dynamic require cannot be bundled: ${id}`);
    for (const match of calls) {
      const specifier = match[2];
      if (specifier.startsWith('node:')) {
        if (!adapters.has(specifier)) throw Error(`Unsupported Node dependency ${specifier} in ${id}`);
        nodeDependencies.add(specifier); dependencies[specifier] = specifier;
      } else {
        if (!specifier.startsWith('.')) throw Error(`External dependencies are not allowed: ${specifier} in ${id}`);
        const resolved = path.resolve(root,path.dirname(id),specifier.endsWith('.js')?specifier:`${specifier}.js`);
        const relative = path.relative(root,resolved).split(path.sep).join('/');
        if (relative.startsWith('../') || path.isAbsolute(relative)) throw Error(`Dependency escapes the source tree: ${id}`);
        dependencies[specifier] = relative; visit(relative);
      }
    }
    if (/\bBuffer\b|\b__dirname\b|\b__filename\b/.test(source)) throw Error(`An unsupported Node global appears in ${id}`);
    const processCalls = [...source.matchAll(/\bprocess\.(\w+)/g)].map(match=>match[1]);
    if (processCalls.some(call=>call!=='memoryUsage')) throw Error(`An unsupported process API appears in ${id}`);
  }
  visit(entry);
  const ids = [...modules.keys()].sort();
  const runtimeFiles = ['scripts/browser-solver/runtime-adapters.js','public/browser-solver-checkpoint-codec.js','scripts/browser-solver/worker-entry.js'];
  const runtimeSources = runtimeFiles.map(id=>({id,source:normalize(fs.readFileSync(path.join(root,id),'utf8'))}));
  const descriptor = {schemaVersion:1,runtimeVersion,entry,builderSha256:hash(normalize(fs.readFileSync(__filename,'utf8'))),
    versions:{adaptive:require('../src/solver/versions').ADAPTIVE_VERSION,solver:require('../src/solver/extensive-solver').VERSION,
      river:require('../src/solver/plo-river-game').VERSION,rules:require('../src/solver/plo-river-game').RULES_VERSION,
      qualification:require('../src/solver/solution-status').VERSION,precision:require('../src/decision-precision').VERSION,
      certificate:require('../src/solver/action-conditioned').VERSION,
      decisionOutcome:require('../src/solver/decision-outcome').VERSION,
      comparisonPolicy:require('../src/solver/decision-outcome').POLICY_VERSION},
    sources:ids.map(id=>({id,sha256:hash(modules.get(id).source),bytes:Buffer.byteLength(modules.get(id).source)})),
    runtimeSources:runtimeSources.map(({id,source})=>({id,sha256:hash(source)})),
    nodeAdapters:[...nodeDependencies].sort(),
    cancellation:'HOST_WORKER_TERMINATE_WITH_COMPLETE_CHECKPOINT_RESUME',
    checkpointTransport:'DETACHED_BINARY64_COPY_TRANSFER_V1',
    memoryMetric:'UNAVAILABLE_IN_BROWSER',sourceNormalization:'LF'};
  const manifest = {...descriptor,buildFingerprint:hash(JSON.stringify(descriptor))};
  const wrappers = ids.map(id=>`${JSON.stringify(id)}: function(module,exports,require,process) {\n${modules.get(id).source}\n}`).join(',\n');
  const maps = Object.fromEntries(ids.map(id=>[id,modules.get(id).dependencies]));
  const source = `// Generated by scripts/build-browser-solver.cjs. Edit the source modules or adapters.\n(function(){\n'use strict';\nconst browserSolverManifest = ${JSON.stringify(manifest)};\n${runtimeSources[0].source}\n${runtimeSources[1].source}\nconst browserModules = {\n${wrappers}\n};\nconst browserDependencyMaps = ${JSON.stringify(maps)};\nconst browserModuleCache = Object.create(null);\nfunction requireBrowserModule(id) {\n  if (Object.hasOwn(browserNodeAdapters,id)) return browserNodeAdapters[id];\n  if (Object.hasOwn(browserModuleCache,id)) return browserModuleCache[id].exports;\n  if (!Object.hasOwn(browserModules,id)) throw Error('Unknown solver module: '+id);\n  const module = {exports:{}}; browserModuleCache[id] = module;\n  browserModules[id](module,module.exports,specifier=>{\n    const target = browserDependencyMaps[id][specifier];\n    if (!target) throw Error('Unknown solver dependency: '+specifier);\n    return requireBrowserModule(target);\n  },browserProcess);\n  return module.exports;\n}\n${runtimeSources[2].source}\n})();\n`;
  return {source,manifest};
}
function main(args=process.argv.slice(2)) {
  if (args.some(arg=>arg!=='--check')) throw Error('Use build-browser-solver.cjs [--check].');
  const output = generate();
  const artifacts = [['public/browser-solver-worker.js',output.source],['public/browser-solver-manifest.json',JSON.stringify(output.manifest,null,2)+'\n']];
  for (const [id,expected] of artifacts) {
    const target = path.join(root,id);
    if (args.includes('--check')) {
      if (!fs.existsSync(target) || normalize(fs.readFileSync(target,'utf8')) !== expected) throw Error(`${id} is stale. Run node scripts/build-browser-solver.cjs.`);
    } else fs.writeFileSync(target,expected);
  }
  console.log(JSON.stringify({status:args.includes('--check')?'CURRENT':'BUILT',buildFingerprint:output.manifest.buildFingerprint,modules:output.manifest.sources.length,workerBytes:Buffer.byteLength(output.source),nodeAdapters:output.manifest.nodeAdapters}));
}
if (require.main===module) { try { main(); } catch(error) { console.error(error.message); process.exitCode=1; } }
module.exports = {generate,normalize};
